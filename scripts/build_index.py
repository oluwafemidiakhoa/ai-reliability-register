#!/usr/bin/env python3
"""Regenerate INDEX.md from the entries. Never edit INDEX.md by hand.

Usage:  python3 scripts/build_index.py

One row per entry: id, date (published, else sealed), target, the claim in one line, outcome,
and whether it was a self-audit. Standard library only.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENTRIES = os.path.join(ROOT, "entries")


def one_line(text, limit=110):
    text = " ".join(str(text).split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def cell(text):
    return str(text).replace("|", "\\|")


def main():
    rows = []
    for name in sorted(f for f in os.listdir(ENTRIES) if f.endswith(".json")):
        with open(os.path.join(ENTRIES, name), encoding="utf-8") as f:
            e = json.load(f)
        s, o = e["sealed"], e["open"]
        date = o.get("published_at") or s.get("sealed_at", "")[:10] or "not sealed"
        rows.append("| [{id}](entries/{name}) | {date} | {target} | {claim} | {outcome} | {self_audit} |".format(
            id=s["id"], name=name, date=date, target=cell(s["target"]["name"]),
            claim=cell(one_line(s["claim"]["text"])), outcome=o.get("outcome") or "open",
            self_audit="yes" if e["auditor"]["self_audit"] else "no"))
    lines = [
        "# Index",
        "",
        "Generated by `scripts/build_index.py` from `entries/`. Do not edit by hand.",
        "",
        "| id | date | target | claim | outcome | self-audit |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
    ]
    with open(os.path.join(ROOT, "INDEX.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"INDEX.md: {len(rows)} entr{'y' if len(rows) == 1 else 'ies'}")


if __name__ == "__main__":
    main()
